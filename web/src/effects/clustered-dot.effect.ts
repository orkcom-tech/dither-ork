// --- screen construction ------------------------------------------------

export class ClusteredDotScreenError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "ClusteredDotScreenError";
  }
}

/** One tile pixel, with everything the growth order sorts on. */
interface Cell {
  readonly x: number;
  readonly y: number;
  /** Squared distance to the nearest dot centre. Exact: every term is a multiple of 1/4. */
  readonly d2: number;
  /** Offset from that centre, used for the angular tie-break. */
  readonly dx: number;
  readonly dy: number;
  /** Which dot claimed it, reduced into the tile so translates count as one. */
  readonly owner: number;
}

/**
 * Identify a dot centre by its position modulo the tile.
 *
 * Centres fall on half-integers when the cell size is odd, so the coordinates
 * are doubled to stay integral before the reduction. Reducing at all is the
 * point: the same dot appears at many lattice indices, and the count check
 * below is asking how many *distinct* dots the tile holds.
 */
function dotKey(cx: number, cy: number, tile: number): number {
  const period = tile * 2;
  const kx = (((cx * 2) % period) + period) % period;
  const ky = (((cy * 2) % period) + period) % period;
  return ky * period + kx;
}

/**
 * Half-plane a direction falls in, splitting at the positive x axis.
 *
 * Half 0 is the angular range `[0, pi)`, half 1 is `[pi, 2pi)`. Together with
 * the cross-product test below this orders directions by angle using only exact
 * arithmetic on half-integers — no `atan2`, whose last bit is not required to
 * agree between platforms and would be the one thing in this construction that
 * could rank two pixels differently on two machines.
 */
function halfPlane(dx: number, dy: number): number {
  return dy > 0 || (dy === 0 && dx > 0) ? 0 : 1;
}

/**
 * The dot-growth order: distance first, then angle, then row and column.
 *
 * The final row/column tie-break is not decoration. On a 45° screen the two
 * dots of a tile are exact translates of each other, so their corresponding
 * pixels agree on distance *and* angle; without a last resort the sort would
 * not be a strict weak ordering and the ranks would depend on the sort's
 * implementation.
 */
function compareCells(a: Cell, b: Cell): number {
  if (a.d2 !== b.d2) return a.d2 - b.d2;
  const ha = halfPlane(a.dx, a.dy);
  const hb = halfPlane(b.dx, b.dy);
  if (ha !== hb) return ha - hb;
  const cross = a.dx * b.dy - a.dy * b.dx;
  if (cross !== 0) return cross > 0 ? -1 : 1;
  if (a.y !== b.y) return a.y - b.y;
  return a.x - b.x;
}

/**
 * Build one screen.
 *
 * @param cell dot spacing in pixels.
 * @param diagonal true for the classical 45° centred-square lattice, false for
 * the axis-aligned one.
 */
function buildScreen(cell: number, diagonal: boolean): {
  readonly tile: number;
  readonly ranks: Uint32Array;
} {
  const tile = diagonal ? cell * 2 : cell;
  const area = tile * tile;
  const expectedPerDot = diagonal ? 2 * cell * cell : cell * cell;

  const cells: Cell[] = [];
  for (let y = 0; y < tile; y += 1) {
    for (let x = 0; x < tile; x += 1) {
      const px = x + 0.5;
      const py = y + 0.5;

      let bestD2 = Number.POSITIVE_INFINITY;
      let bestDx = 0;
      let bestDy = 0;
      let bestCx = 0;
      let bestCy = 0;

      // A window of two lattice steps either side of the pixel always contains
      // the nearest centre for both lattices; the loop is cheap enough that
      // widening it costs nothing and narrowing it would need a proof.
      const u0 = Math.floor((px - cell / 2) / cell) - 2;
      const v0 = Math.floor((py - cell / 2) / cell) - 2;
      for (let v = v0; v <= v0 + 4; v += 1) {
        for (let u = u0; u <= u0 + 4; u += 1) {
          // The 45° lattice is the subset of the square lattice whose two
          // indices share a parity — the centred-square lattice generated by
          // (n, n) and (n, -n).
          if (diagonal && (((u + v) % 2) + 2) % 2 !== 0) continue;
          const cx = u * cell + cell / 2;
          const cy = v * cell + cell / 2;
          const dx = px - cx;
          const dy = py - cy;
          const d2 = dx * dx + dy * dy;
          // Ties are broken on the centre's own position, which is invariant
          // under the lattice translations that map one dot of the tile onto
          // the other — so both dots come out the same shape and the same size.
          const better =
            d2 < bestD2 ||
            (d2 === bestD2 && (cy < bestCy || (cy === bestCy && cx < bestCx)));
          if (better) {
            bestD2 = d2;
            bestDx = dx;
            bestDy = dy;
            bestCx = cx;
            bestCy = cy;
          }
        }
      }

      cells.push({
        x,
        y,
        d2: bestD2,
        dx: bestDx,
        dy: bestDy,
        owner: dotKey(bestCx, bestCy, tile),
      });
    }
  }

  const counts = new Map<number, number>();
  for (const c of cells) counts.set(c.owner, (counts.get(c.owner) ?? 0) + 1);
  for (const [owner, count] of counts) {
    if (count !== expectedPerDot) {
      // A lattice or tie-break mistake shows up here as unequal dots, which
      // would otherwise be a screen that halftones, looks broadly right, and
      // reproduces tone wrong in one of its two dots.
      throw new ClusteredDotScreenError(
        `clustered-dot ${diagonal ? "45" : "0"}deg cell ${cell}: dot ${owner} owns ${count} pixels, expected ${expectedPerDot}`,
      );
    }
  }
  if (counts.size !== area / expectedPerDot) {
    throw new ClusteredDotScreenError(
      `clustered-dot ${diagonal ? "45" : "0"}deg cell ${cell}: tile holds ${counts.size} dots, expected ${area / expectedPerDot}`,
    );
  }

  const order = [...cells].sort(compareCells);
  const ranks = new Uint32Array(area);
  const seen = new Uint8Array(area);
  order.forEach((c, rank) => {
    const at = c.y * tile + c.x;
    if (seen[at] === 1) {
      throw new ClusteredDotScreenError(
        `clustered-dot cell ${cell}: pixel ${c.x},${c.y} was ranked twice`,
      );
    }
    seen[at] = 1;
    ranks[at] = rank;
  });

  return { tile, ranks };
}

/**
 * The whole family, packed as the shader reads it.
 *
 * Layout, all u32: a four-word header (`screenCount`, `minCell`, `sizeCount`,
 * `modeCount`), then two words per screen (`tile`, word offset of its ranks),
 * then the ranks. See `../shaders/clustered-dot.wgsl` for the reading side.
 */
export function buildClusteredDotScreens(): Uint32Array {
  const built: { tile: number; ranks: Uint32Array }[] = [];
  for (const mode of ANGLE_MODES) {
    for (let cell = MIN_CELL; cell <= MAX_CELL; cell += 1) {
      built.push(buildScreen(cell, mode.value === "diagonal"));
    }
  }

  const directory = built.length * 2;
  const dataWords = built.reduce((total, screen) => total + screen.ranks.length, 0);
  const words = new Uint32Array(HEADER_WORDS + directory + dataWords);

  words[0] = built.length;
  words[1] = MIN_CELL;
  words[2] = SIZE_COUNT;
  words[3] = ANGLE_MODES.length;

  let cursor = HEADER_WORDS + directory;
  built.forEach((screen, index) => {
    words[HEADER_WORDS + index * 2] = screen.tile;
    words[HEADER_WORDS + index * 2 + 1] = cursor;
    words.set(screen.ranks, cursor);
    cursor += screen.ranks.length;
  });

  log.debug("clustered-dot screens built", {
    screens: built.length,
    bytes: words.byteLength,
  });
  return words;
}

/** Built once and kept: the table is constant and the sorts are not free. */
let screenTable: Uint32Array | null = null;

function clusteredDotScreenBytes(): Uint8Array {
  if (screenTable === null) screenTable = buildClusteredDotScreens();
  // A view, not a copy. Uint32Array already uses host byte order and WebGPU
  // buffer contents are host byte order, so the shader's array<u32> reads
  // exactly these words.
  return new Uint8Array(screenTable.buffer, screenTable.byteOffset, screenTable.byteLength);
}

/**
 * The compute pass.
 *
 * One dispatch, pointwise: the threshold comes from the pixel's own coordinate
 * and nothing is read from a neighbour.
 */
export function clusteredDotGpuEffect(): GpuEffect {
  const bindings: readonly PassBinding[] = [
    { role: "input-color", binding: BINDING.inputColor },
    { role: "output-color", binding: BINDING.outputColor },
    { role: "output-index", binding: BINDING.outputIndex },
    { role: "palette", binding: BINDING.palette },
    { role: "uniforms", binding: BINDING.uniforms },
    { role: "table", binding: BINDING.screens, data: clusteredDotScreenBytes() },
  ];

  const pass: ComputePass = {
    id: `${CLUSTERED_DOT_ID}/screen`,
    label: "Clustered-dot screen",
    wgsl,
    entryPoint: "main",
    // 64 invocations, well under the 256 guaranteed everywhere.
    workgroupSize: [8, 8, 1],
    dispatch: { kind: "per-pixel" },
    access: "pointwise",
    bindings,
    uniforms: CLUSTERED_DOT_UNIFORMS,
  };

  return { effect: CLUSTERED_DOT_ID, passes: [pass] };
}

