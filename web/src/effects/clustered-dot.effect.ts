/**
 * F-PT-07 — Classical clustered-dot ordered screen.
 *
 * ## What the screen is, and where it comes from
 *
 * A clustered-dot screen is the printing screen: at every tone the pixels that
 * are on form one compact dot per screen cell, and the dot grows outward from
 * the cell centre as the tone darkens. It is the exact opposite of Bayer, whose
 * recursion maximally *disperses* the same pixels, and it cannot be reached by
 * blurring or reordering a Bayer tile.
 *
 * The family is classically published as a set of integer threshold matrices —
 * Ulichney, *Digital Halftoning* (1987) §5.1, and the same tables reproduced in
 * Netpbm as `cluster3`/`cluster4`/`cluster8`. **The tables are not transcribed
 * here; they are constructed from the definition they are tabulations of**,
 * which is what lets the effect offer the whole family rather than the three
 * sizes that happen to be in print, and what removes the risk of a mistyped
 * cell in a hand-copied matrix:
 *
 * 1. Dot centres sit on a lattice. `orthogonal` uses the axis-aligned lattice
 *    with spacing `cell`, so the tile is `cell × cell` and holds one dot.
 *    `diagonal` uses the centred-square lattice generated by `(n, n)` and
 *    `(n, −n)`, the classical 45° screen: its cells hold `2n²` pixels, its
 *    smallest axis-aligned period is `2n × 2n`, and that tile holds two dots.
 *    (That is exactly the structure of the published tables, whose values each
 *    appear twice.)
 * 2. Every pixel of the tile is ordered by distance from its nearest dot
 *    centre, ties broken by the angle about that centre — the spiral growth the
 *    family is named for — and finally by row then column, so the order is a
 *    strict total order and the result is reproducible.
 * 3. Rank `k` of `A` becomes the threshold `(k + 0.5) / A`.
 *
 * Because the ranks are a permutation, the thresholds are uniformly distributed
 * over the tile and the screen reproduces tone exactly. The published tables
 * give the two dots of a 45° tile equal values; ranking the whole tile splits
 * those ties into adjacent levels instead, which is the same screen with twice
 * the tonal resolution and at most a one-pixel difference in dot size at any
 * given tone.
 *
 * Where the published matrices start their spiral is a convention — rotating
 * the growth order rotates the dot and changes nothing tonal — so this
 * construction reproduces their level sets, not necessarily their exact
 * numbering.
 *
 * ## Why the whole family ships as one table
 *
 * A `table` binding is uploaded once when the pipeline is compiled and cannot
 * change per parameter, but cell size and angle *are* parameters. So every
 * screen is concatenated into one buffer behind a header and the uniform picks
 * one. It costs about 30 KB and it keeps the effect a single registry entry
 * instead of thirty.
 */

